"""Many-shot memory injection attack.

Tests whether planting MULTIPLE poisoned memories (instead of one, like
direct_injection.py) makes the attack more likely to win at retrieval time
and/or more likely to convince the model, given the agent only ever looks
at its top_k=3 closest memories per question.

Two arms:
  Arm A ("volume")    -- plant K identical copies of the same poisoned fact.
                          Swept at K = 1, 2, 3 only. Beyond K=3 this CANNOT
                          change the top-3 retrieval result (only 3 slots
                          exist, and identical text always has identical
                          distance), so K=5/K=10 would waste trials here.
  Arm B ("diversity")  -- plant K different phrasings of the same poisoned
                          claim (auto-generated by the local model). Swept
                          at K = 1, 3, 5, 10 (PoisonedRAG's reference
                          points), since different phrasings sit at
                          different distances and keep getting new chances
                          to land in top-3 as K grows.

This run is a SMOKE TEST (n_trials=1 by default) meant to confirm the code
path works end to end -- unique IDs per poison copy, the multi-ID ISR
check, paraphrase generation, and judge calls -- before committing to the
full-scale sweep. Re-run with --n_trials set higher once this checks out.

Domains: one shared with the existing MINJA sweep (driving_license, for a
direct attack-type comparison) and one never run before (wifi_password_
sharing, for coverage / to avoid the ceiling effect seen in peanut_allergy
and medication_dosage under MINJA).

WITH-contradiction only (true fact present) -- the harder, more realistic
condition, matching the plan discussed with the user.

Outputs (all written to disk, nothing terminal-only):
  results/many_shot_smoke_<timestamp>.json              -- all trial data
  results/many_shot_smoke_paraphrases_<timestamp>.json  -- generated Arm B
                                                            phrasings, for
                                                            manual spot-check
  logs/many_shot_smoke_<timestamp>.log                  -- full run log
"""
