    logger.info(f"Command: {' '.join(sys.argv)}")
    logger.info(f"Domains: {[d['name'] for d in selected_domains]} | Arm A K={ARM_A_K_VALUES} | Arm B K={ARM_B_K_VALUES} | n_trials={args.n_trials}")

    results_filename = f"results/many_shot_{tag}_{timestamp}.json"
    paraphrase_filename = f"results/many_shot_{tag}_paraphrases_{timestamp}.json"

    all_trials = []
